import sys
from collections import OrderedDict
from pathlib import Path

USAGE = "usage: python3 tools/flipper_ir.py tools/flipper > rs/src/irdb.rs"
U16_MAX = 65535

REMOTES = [
    ("tv", "TV", ["Power", "Vol_up", "Vol_dn", "Mute", "Ch_next", "Ch_prev"]),
    ("audio", "Audio", ["Power", "Vol_up", "Vol_dn", "Mute", "Play", "Pause", "Next", "Prev"]),
    ("projector", "Projector", ["Power", "Vol_up", "Vol_dn", "Mute"]),
    ("ac", "Air con", ["Off", "Cool_lo", "Cool_hi", "Heat_lo", "Heat_hi", "Dh"]),
]
FLIPPER_TO_RUST_PROTOCOL = {
    "NEC": "Nec", "NECext": "NecExt", "NEC42": "Nec42", "Samsung32": "Samsung32",
    "SIRC": "Sirc12", "SIRC15": "Sirc15", "SIRC20": "Sirc20", "RC5": "Rc5", "RC5X": "Rc5x",
    "RC6": "Rc6", "Kaseikyo": "Kaseikyo", "RCA": "Rca", "Pioneer": "Pioneer",
}
HEADER = [
    "// Generated by tools/flipper_ir.py from the Flipper Zero universal remote database",
    "// (see tools/flipper/SOURCE.txt, GPL-3.0). Do not edit.",
    "use crate::ir::{Button, Code, Protocol, Remote};",
    "",
    "pub static REMOTES: &[Remote] = &[",
]


def records(path):
    record = {}
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("#"):
            if "name" in record:
                yield record
            record = {}
        elif ":" in line:
            key, value = line.split(":", 1)
            record[key.strip()] = value.strip()
    if "name" in record:
        yield record


def little_endian_hex(hex_bytes):
    return int.from_bytes(bytes.fromhex(hex_bytes.replace(" ", "")), "little")


def parsed_code(record):
    protocol = FLIPPER_TO_RUST_PROTOCOL.get(record["protocol"])
    if protocol is None:
        return None
    address = little_endian_hex(record["address"])
    command = little_endian_hex(record["command"])
    return f"Code::Parsed(Protocol::{protocol}, 0x{address:x}, 0x{command:x})"


def raw_code(record):
    durations_clamped_to_u16 = ",".join(str(min(int(v), U16_MAX)) for v in record["data"].split())
    return f"Code::Raw({int(float(record['frequency']))}, &[{durations_clamped_to_u16}])"


def code(record):
    return parsed_code(record) if record["type"] == "parsed" else raw_code(record)


def collect_buttons(path, order):
    buttons = OrderedDict((name, []) for name in order)
    skipped = 0
    for record in records(path):
        button_code = code(record)
        if record["name"] in buttons and button_code:
            buttons[record["name"]].append(button_code)
        else:
            skipped += 1
    return buttons, skipped


def remote_lines(title, buttons):
    lines = [f'    Remote {{ name: "{title}", buttons: &[']
    for name, codes in buttons.items():
        lines.append(f'        Button {{ name: "{name.replace("_", " ")}", codes: &[')
        lines += [f"            {c}," for c in codes]
        lines.append("        ] },")
    lines.append("    ] },")
    return lines


def report(title, buttons, skipped):
    counts = ", ".join(f"{name} {len(codes)}" for name, codes in buttons.items())
    print(f"{title}: {counts}, skipped {skipped}", file=sys.stderr)


def main(source_dir):
    out = list(HEADER)
    for file, title, order in REMOTES:
        buttons, skipped = collect_buttons(Path(source_dir) / f"{file}.ir", order)
        report(title, buttons, skipped)
        out += remote_lines(title, buttons)
    out.append("];")
    print("\n".join(out))


if len(sys.argv) != 2:
    sys.exit(USAGE)
main(sys.argv[1])
